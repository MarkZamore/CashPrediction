package ru.cashprediction.core.json;

/**
 * Ошибка разбора, записи или чтения полей JSON.
 *
 * <p>Исключение непроверяемое: JSON в программе появляется в двух местах (web-API и снимок сессии
 * в реестре), и в обоих случаях вызывающий код ловит его в одной точке и превращает в понятное
 * пользователю сообщение. Проверяемое исключение заставило бы протаскивать {@code throws} через
 * каждый маленький метод-аксессор {@link Json}.</p>
 *
 * <p>Сообщение об ошибке данных берётся из каталога текстов (область {@code json}) и, если ошибка связана с текстом,
 * содержит строку, столбец и позицию, например: «Некорректный JSON, строка 1, столбец 9 (позиция 8): ожидалось «:»».
 * Ошибки программиста при записи ({@link JsonWriter}) описываются латиницей для разработчика.</p>
 *
 * <p>Экземпляры неизменяемы и потокобезопасны.</p>
 */
public final class JsonException extends RuntimeException {

    /** Смещение символа в исходном тексте, начиная с 0; -1, если ошибка не связана с позицией. */
    private final int position;

    /**
     * Создаёт ошибку, не привязанную к позиции в тексте (например, неверный тип поля).
     *
     * @param message сообщение на русском
     */
    public JsonException(String message) {
        super(message);
        this.position = -1;
    }

    /**
     * Создаёт ошибку разбора в указанной позиции текста.
     *
     * @param message  полное сообщение на русском (уже содержит координаты)
     * @param position смещение символа в тексте, начиная с 0
     */
    public JsonException(String message, int position) {
        super(message);
        this.position = position;
    }

    /**
     * Возвращает позицию ошибки.
     *
     * @return смещение символа от начала текста (с 0) или -1, если позиция неприменима
     */
    public int position() {
        return position;
    }
}
