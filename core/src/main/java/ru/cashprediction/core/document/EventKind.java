package ru.cashprediction.core.document;

/**
 * Что именно изменилось в открытом документе {@link PlanDocument}.
 *
 * <p>Клиенты подписываются на события документа и по набору видов решают, что перерисовать:
 * при {@link #PLAN} — таблицу, график и сводку; при {@link #VIEW} — только видимую часть;
 * при {@link #FILE} и {@link #DIRTY} — заголовок окна и строку состояния.</p>
 */
public enum EventKind {
    /** Изменился сам план (правка, отмена, повтор, открытие другого плана). */
    PLAN,
    /** Изменились параметры отображения {@link ViewState}. */
    VIEW,
    /** Изменился файл, связанный с документом (открытие, «Сохранить как»). */
    FILE,
    /** Изменился признак несохранённых изменений. */
    DIRTY
}
