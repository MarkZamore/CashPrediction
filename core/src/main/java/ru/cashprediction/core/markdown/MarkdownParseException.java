package ru.cashprediction.core.markdown;

/**
 * Текст вообще не является планом CashPrediction: в нём нет ни заголовка {@code # План:},
 * ни одной известной секции.
 *
 * <p>Это единственный случай, когда читатель отказывается строить план. Любые другие проблемы
 * (испорченная сумма, неизвестная секция) превращаются в диагностику, а не в исключение.</p>
 *
 * <p>Исключение непроверяемое: оно возникает только при попытке открыть посторонний файл
 * (например, {@code settings.md} или чужую заметку), и вызывающему коду достаточно поймать его там же,
 * где он показывает ошибку открытия файла. Сообщение на русском и пригодно для показа пользователю.</p>
 */
public class MarkdownParseException extends RuntimeException {

    private static final long serialVersionUID = 1L;

    /**
     * Создаёт исключение с сообщением для пользователя.
     *
     * @param message текст на русском
     */
    public MarkdownParseException(String message) {
        super(message);
    }
}
