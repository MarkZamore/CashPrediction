package ru.cashprediction.core.forecast;

/**
 * Вид предупреждения прогноза. Позволяет интерфейсу группировать и фильтровать предупреждения,
 * не разбирая русский текст сообщения.
 */
public enum WarningType {
    /** Баланс уходит в минус. */
    NEGATIVE_BALANCE("Отрицательный баланс"),
    /** Баланс опускается ниже подушки безопасности. */
    BELOW_CUSHION("Ниже подушки безопасности"),
    /** Корректировка не относится ни к одному событию. */
    ORPHAN_ADJUSTMENT("Корректировка без события"),
    /** Корректировка перенесла событие за пределы горизонта. */
    MOVED_OUT_OF_HORIZON("Перенос за горизонт"),
    /** Окно «С/По» правила не пересекается с горизонтом. */
    RULE_OUTSIDE_HORIZON("Правило вне горизонта"),
    /** Несколько корректировок одного события. */
    DUPLICATE_ADJUSTMENT("Повторная корректировка"),
    /** Цель не достигается (или достигается позже желаемой даты). */
    GOAL_NOT_REACHED("Цель не достигнута"),
    /** Разовая операция за пределами горизонта. */
    ONE_TIME_OUTSIDE_HORIZON("Разовая операция вне горизонта");

    private final String title;

    WarningType(String title) {
        this.title = title;
    }

    /** @return подпись для интерфейса */
    public String title() {
        return title;
    }
}
