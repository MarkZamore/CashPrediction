package ru.cashprediction.core.forecast.service;

import ru.cashprediction.core.forecast.Forecast;

/**
 * Локальная граница расчёта прогноза: вход и результат неизменяемы, служба не владеет планом или его историей.
 *
 * <p>Реализация возвращает ненулевой Forecast для переданного снимка, даты и параметров. Служба не читает часы,
 * не меняет запрос, не хранит состояние документа и не обращается к UI или хранилищу. Кэш принадлежит потребителю.
 * Версия 1 обозначает нынешний алгоритм календарных событий: прежние фазы повторов, сдвиги выходных,
 * корректировки, порядок строк, округление HALF_UP и суммы в minor units. Изменение этой семантики требует
 * новой версии, а не скрытого изменения реализации. Это не версия файлов или сетевого протокола.</p>
 *
 * <p>Ожидаемые ошибки имеют типы ForecastFailure: предел ресурсов, переполнение сумм, недопустимая граница
 * Money и диапазон дат.
 * Они сохраняют исходную причину, сообщение и семейство исключения JDK. Ошибки программирования, например
 * null вместо запроса, не маскируются под бизнес-ошибку. Контракт не добавляет транспорт или микросервисы.</p>
 */
@FunctionalInterface
public interface ForecastService {
    /** Версия существующей семантики расчёта. */
    int ALGORITHM_VERSION = 1;

    /**
     * Рассчитывает снимок с явно заданными параметрами.
     *
     * @param request неизменяемый запрос
     * @return неизменяемый результат; массив ежедневных балансов защищён копиями в Forecast
     * @throws ForecastFailure.LimitExceeded если превышен предел горизонта или числа дат
     * @throws ForecastFailure.AmountOverflow если денежный результат не помещается в minor units long
     * @throws ForecastFailure.AmountOutOfRange если денежный результат равен запрещённому Long.MIN_VALUE
     * @throws ForecastFailure.DateRangeExceeded если календарная операция выходит за диапазон LocalDate
     */
    Forecast calculate(ForecastRequest request);

    /** @return версия семантики реализации; совместимые реализации используют версию 1 */
    default int algorithmVersion() {
        return ALGORITHM_VERSION;
    }
}
