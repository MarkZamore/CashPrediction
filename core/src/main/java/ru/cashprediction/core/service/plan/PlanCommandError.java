package ru.cashprediction.core.service.plan;

/** Машинные коды отказа команды; русское объяснение передаётся отдельно из общего каталога. */
public enum PlanCommandError {
    /** Запрос относится к прежнему состоянию плана. */
    STALE_REVISION,
    /** Идентификатор уже использован для другого запроса. */
    REQUEST_ID_REUSED,
    /** Синхронный слушатель попытался изменить план внутри выполняемой команды. */
    COMMAND_IN_PROGRESS,
    /** Отсутствует обязательное значение предметной команды. */
    INVALID_COMMAND,
    /** Указанного объекта больше нет. */
    NOT_FOUND,
    /** Добавление заняло уже используемый идентификатор. */
    DUPLICATE_ID,
    /** Сумма не удовлетворяет ограничениям операции. */
    INVALID_AMOUNT,
    /** Интервал действия правила противоречит расписанию. */
    INVALID_RECURRENCE,
    /** Корректировка не относится к существующему номинальному событию. */
    INVALID_ADJUSTMENT,
    /** Результат команды нарушает общие ограничения плана. */
    INVALID_PLAN,
    /** Предметный расчёт не смог построить результат. */
    CALCULATION_FAILED,
    /** План изменён, но один из синхронных подписчиков завершился с ошибкой. */
    NOTIFICATION_FAILED
}
