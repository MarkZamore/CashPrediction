package ru.cashprediction.core.service.plan;

/**
 * Граница владельца текущего плана и истории в модульном монолите.
 * Передаёт только неизменяемые данные; не раскрывает документ, функцию изменения или UI-сеанс.
 * Вызовы локальной реализации выполняются последовательно в потоке владельца документа.
 */
public interface PlanCommands {
    /** @return текущие данные и предметная ревизия для последующей команды */
    PlanCommandSnapshot snapshot();

    /**
     * Проверяет ожидаемую ревизию, данные и результат до единственного шага истории.
     * Повтор идентичного запроса возвращает первоначальный результат в пределах окна дедупликации.
     *
     * @param request неизменяемый запрос
     * @return результат либо структурированный отказ
     */
    PlanCommandResult execute(PlanCommandRequest request);

    /**
     * Проверяет и рассчитывает проект результата без изменения плана, истории, ревизии и окна повторов.
     * Отмена и повтор допускаются только в execute.
     *
     * @param request запрос с текущей ожидаемой ревизией
     * @return проверенный проект либо отказ; ревизия проекта равна исходной
     */
    PlanCommandResult preview(PlanCommandRequest request);
}
