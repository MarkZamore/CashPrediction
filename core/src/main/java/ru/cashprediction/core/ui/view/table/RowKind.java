package ru.cashprediction.core.ui.view.table;

/**
 * Вид строки таблицы прогноза (спецификация v2, §5.2).
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum RowKind {
    /** Группа «Прошедшие события» перед первой прошедшей строкой; текст в объединённой ячейке «Дата…Категория». */
    PAST_HEADER,
    /** Начальный баланс плана; никогда не прошедшая. */
    START,
    /** Событие регулярной операции. */
    RULE,
    /** Разовая операция. */
    ONE_TIME,
    /** Доп. экономия «что-если». */
    WHAT_IF,
    /** Итог месяца (при флажке «Итоги по месяцам»). */
    MONTH_TOTAL
}
