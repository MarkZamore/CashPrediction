package ru.cashprediction.core.ui.command;

/**
 * Где находится фокус клавиатуры в момент нажатия (спецификация v2, §7, колонка «Где работает»).
 *
 * <p>Клиент определяет область по виджету с фокусом и передаёт её в {@code UiIntents.key} вместе с {@code focusId}
 * (id карточки для {@link #CARD}, id окна для {@link #TEXT_INPUT} и {@link #POPUP}, иначе пустая строка); ядро
 * решает, действует ли сочетание в этой области. Например, Enter и Delete работают только в {@link #TABLE}, Ctrl+Z —
 * не в {@link #TEXT_INPUT}, Esc очищает фильтр только в {@link #FILTER}.</p>
 *
 * <p><b>Enter и Esc внутри окон форм</b> (диалоги, калькулятор цели, быстрая правка) в {@code HotkeyTable} не входят:
 * клиент передаёт их сеансу формы ({@code FormSession.fieldSubmitted} / {@code closeRequested}), см.
 * {@code FormSession}. Области {@link #TEXT_INPUT} и {@link #POPUP} нужны остальным сочетаниям, которые «везде»
 * действуют и в немодальных окнах (Ctrl+S, Ctrl+F, F1).</p>
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum FocusScope {

    /** Главное окно вне таблицы, фильтра и полей ввода (тулбар, график, строка состояния). */
    MAIN,
    /** Таблица прогноза. */
    TABLE,
    /** Поле фильтра тулбара. */
    FILTER,
    /** Поле ввода немодального окна (калькулятор цели) или спиннер меню. */
    TEXT_INPUT,
    /** Карточка сводки ({@code focusId} — id карточки). */
    CARD,
    /** Всплывающее окно быстрой правки суммы ({@code focusId} — id окна). */
    POPUP
}
