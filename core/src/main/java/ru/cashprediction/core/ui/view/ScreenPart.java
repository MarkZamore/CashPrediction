package ru.cashprediction.core.ui.view;

/**
 * Часть главного окна, которую клиент перерисовывает независимо (архитектура §3.4). Контроллер хеширует каждую
 * часть {@link MainScreenModel} и передаёт в {@code UiPort.render} только изменившиеся.
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum ScreenPart {
    /** Заголовок окна ({@code main.title} / {@code main.title.dirty}). */
    TITLE,
    /** Строка меню. */
    MENU,
    /** Тулбар. */
    TOOLBAR,
    /** Панель сводки. */
    SUMMARY,
    /** Таблица (модель новой ревизии). */
    TABLE,
    /** График (модель новой ревизии). */
    CHART,
    /** Строка состояния. */
    STATUS,
    /** Режим центральной области: таблица или график. */
    MODE
}
