package ru.cashprediction.core.ui.command;

/**
 * Откуда пришла команда. Нужен правилу модальности (архитектура §3.7): пока открыто модальное окно, команды
 * главного окна ({@link #isMainWindow()}) ядро игнорирует.
 *
 * <p><b>Правило модальности по источникам</b> (выполняет {@code AppController.command}):</p>
 * <ul>
 *   <li>{@link #MENU}, {@link #TOOLBAR}, {@link #CONTEXT_MENU}, {@link #HOTKEY}, {@link #MAIN}, {@link #SELFTEST} —
 *       игнорируются, пока открыто хоть одно модальное окно;</li>
 *   <li>{@link #FORM} — команда из открытой формы (контекстное меню списка предпросмотра редактора правила, §6.3):
 *       {@code CommandArgs.key} — id окна формы; команда выполняется, только если это окно — верхнее модальное окно
 *       или модальных окон нет (немодальная форма). Иначе игнорируется.</li>
 * </ul>
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum InvokeSource {

    /** Строка меню главного окна. */
    MENU,
    /** Тулбар. */
    TOOLBAR,
    /** Контекстное меню главного окна (строка, итог, группа прошедших, карточка, график). */
    CONTEXT_MENU,
    /** Горячая клавиша (диспетчер {@code HotkeyTable}). */
    HOTKEY,
    /** Прочие действия главного окна: двойной щелчок, кнопки пустого состояния, щелчок по группе прошедших. */
    MAIN,
    /**
     * Контекстное меню или иной элемент внутри открытой формы (например «Скорректировать эту дату…» в предпросмотре
     * редактора правила, {@link CommandId#PREVIEW_ADJUST}); {@code CommandArgs.key} — id окна формы.
     */
    FORM,
    /**
     * Шаг сценария самотеста, который ядро выполняет само (например {@code sample}, {@code snapshot}). Подчиняется
     * модальности так же, как пользователь: драйвер самотеста не может сделать того, чего не может человек.
     */
    SELFTEST;

    /**
     * Относится ли источник к главному окну (такие команды блокируются модальным окном).
     *
     * @return {@code true} для всех источников, кроме {@link #FORM}
     */
    public boolean isMainWindow() {
        return this != FORM;
    }
}
