package ru.cashprediction.core.ui.view.chart;

/**
 * Горизонтальная привязка текста к точке (как {@code text-anchor} в SVG); вертикально точка — базовая линия.
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum TextAnchor {
    /** Текст начинается в точке. */
    START,
    /** Центр текста в точке. */
    MIDDLE,
    /** Текст заканчивается в точке. */
    END
}
