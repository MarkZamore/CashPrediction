package ru.cashprediction.core.ui.form;

/**
 * Роль кнопки панели кнопок (спецификация v2, §6.0 «Роли кнопок»). Порядок кнопок задан списком
 * {@code FormSpec.buttons} явно, без сортировки по ролям: LEFT прижаты влево, остальные справа по порядку,
 * CANCEL последняя.
 *
 * <p>JavaFX: {@code ButtonType} с {@code ButtonBar.ButtonData} из роли и {@code BUTTON_ORDER_NONE} → Swing:
 * {@code JButton} в панели → Web: {@code button}.</p>
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum ButtonRole {

    /** Подтверждающая: по умолчанию Enter, выделена {@code accent}; отключена, пока есть ошибка. */
    OK,
    /** Отмена: Esc и крестик окна. */
    CANCEL,
    /** Прочая кнопка справа («Не сохранять», «Перечитать»). */
    OTHER,
    /** Кнопка слева («Открыть пример», «Сбросить корректировку», «Записать цель в план»). */
    LEFT,
    /** «‹ Назад» мастера. */
    BACK,
    /** «Далее ›» мастера. */
    NEXT,
    /** «Готово» мастера. */
    FINISH
}
