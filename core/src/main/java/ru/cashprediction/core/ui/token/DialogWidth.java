package ru.cashprediction.core.ui.token;

/**
 * Минимальная ширина контента диалогов по их виду (спецификация v2, §1.3).
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum DialogWidth {

    /** Сообщение, подтверждение, ввод текста, выбор из списка: 460. */
    ALERT(460),
    /** Форма: разовая операция, корректировка, CSV, параметры плана, «Открыть план»: 560. */
    FORM(560),
    /** Мастер нового плана: 600. */
    WIZARD(600),
    /** Калькулятор цели: 640. */
    GOAL(640),
    /** Редактор правила с колонкой предпросмотра: 880. */
    RULE(880),
    /** Восстановление сеанса после сбоя: 720. */
    RECOVERY(720),
    /** Справка и последний снимок (с подробностями): 760. */
    HELP(760),
    /** Окно ядра «Выбор файла» web-клиента: 680. */
    FILE_BROWSER(680);

    private final int px;

    DialogWidth(int px) {
        this.px = px;
    }

    /** @return ширина контента в пикселях при масштабе 1,0 */
    public int px() {
        return px;
    }
}
