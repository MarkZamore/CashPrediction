package ru.cashprediction.core.app;

/**
 * Как показать строку таблицы ({@code UiPort.revealRow}; спецификация v2, §5.1 «Показать в таблице», §5.2
 * «Прокрутка при открытии плана»).
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum RevealMode {

    /**
     * Прокрутить так, чтобы строка стала верхней видимой, выделение не менять. После открытия плана и смены
     * периода — к первой строке с датой ≥ сегодня.
     */
    SCROLL_TO_TOP,
    /**
     * Выделить строку и прокрутить к ней, если она не видна. «Показать в таблице», восстановление выделения после
     * сбоя, переход к строке после правки.
     */
    SELECT_AND_SCROLL
}
