package ru.cashprediction.core.app;

/**
 * Состояние записи сеанса для строки состояния и доступности команд меню «Восстановление»
 * (спецификация v2, §5.4 сегмент session, §6.27, §6.28).
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum RecorderStatus {

    /** Запись ещё не начата (до первого показа окна или до ответа на диалог восстановления). */
    NOT_STARTED,
    /** Ожидает решения о восстановлении: «Ожидает решения о восстановлении». */
    PENDING_RESTORE,
    /** Запись идёт: сегмент показывает время последней записи по хранилищам. */
    RECORDING,
    /** Второй экземпляр: «Запись сеанса отключена (второй экземпляр)», «Сделать снимок сейчас» даёт {@code info.recordingOff}. */
    DISABLED_SECOND_INSTANCE
}
