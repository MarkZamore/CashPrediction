package ru.cashprediction.core.app;

/**
 * Куда клиент переводит фокус клавиатуры по требованию ядра ({@code UiPort.focus}).
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum FocusTarget {

    /** Таблица прогноза: при открытии окна (§2), Enter в поле фильтра (§4). */
    TABLE,
    /** Поле фильтра тулбара с выделением текста: «Перейти к фильтру», Ctrl+F (§3.3). */
    FILTER,
    /** Строка меню: F10 (§7). FX — первое меню, Swing — {@code MenuSelectionManager}, web — первый пункт menubar. */
    MENU_BAR,
    /** Область графика (после переключения на график с клавиатуры). */
    CHART
}
