package ru.cashprediction.core.app;

/**
 * Как завершается процесс ({@code UiPort.exit}; спецификация v2, §6.30, §6.32, §6.33).
 *
 * <p>Перечисление неизменяемо и потокобезопасно.</p>
 */
public enum ExitKind {

    /** Обычный выход после {@code ExitFlow}: окна закрыты, настройки записаны, маркер сеанса {@code closed}. */
    CLEAN,
    /**
     * Аварийная остановка {@code Runtime.halt(code)} без сохранения: «Симулировать сбой» (код 3) и
     * «Закрыть программу» после необработанной ошибки (код 2). Маркер сеанса остаётся {@code running}.
     */
    HALT,
    /** Web: сервер остановлен после «Выход»; вкладки показывают экран «CashPrediction остановлен» (§6.30). */
    WEB_STOPPED,
    /** Web: сервер остановлен аварийно; вкладки показывают «Сервер остановлен аварийно» (§6.30). */
    WEB_CRASHED
}
