package ru.cashprediction.core.session;

/**
 * Источник состояния главного окна и плана для снимка; реализуется контроллером клиента.
 *
 * <p>Открытые диалоги рекордер опрашивает сам через зарегистрированные {@link StatefulWindow},
 * а всё, что относится к главному окну и документу плана, отдаёт этот источник.</p>
 *
 * <p>Оба метода вызываются только в UI-потоке клиента.</p>
 */
public interface SnapshotSource {

    /**
     * Снимает состояние главного окна.
     *
     * @return состояние главного окна
     */
    MainWindowState captureMain();

    /**
     * Снимает состояние плана: при несохранённых изменениях — полный Markdown-текст.
     *
     * @return состояние плана
     */
    PlanState capturePlan();
}
