/**
 * Установка управляемого дерева с независимым от JVM помощником Windows PowerShell.
 *
 * <p>Служебные пути восстановителя выводятся из проверенного корня, а журнал содержит
 * только относительные управляемые пути. Файлы вне этого инвентаря не удаляются.
 * Перед переносами проверяются leases и реальные пути всех подходящих процессов,
 * включая незарегистрированные JVM и оба процесса jpackage.</p>
 *
 * <p>Скрипт {@code CashMemory/Updates/apply-update.ps1 -InstallationRoot <root>}
 * восстанавливает дерево без runtime приложения. Portable-журнал схемы 2 сначала
 * копирует весь старый runtime и проверяет его, затем перенаправляет три cfg
 * через {@code app.runtime=$ROOTDIR\CashMemory\Updates\Bootstrap\runtime}.
 * Исходные exe, cfg и .jpackage.xml всегда остаются на своих путях: резервные
 * копии создаются копированием, а замена выполняется атомарным File.Replace.
 * Поэтому обычный exe может загрузить старый S7 lifecycle из целой копии JDK,
 * пока основной runtime частично перенесён. Главный модуль и APPDIR сохраняются.
 * После проверки нового дерева cfg возвращаются к штатному runtime, и лишь
 * после проверки всех cfg и отсутствия процессов можно удалить bootstrap.</p>
 *
 * <p>Проверка процессов также не является атомарным барьером создания новой JVM:
 * запуск может попасть между census и переносом. ОС откажет в переносе занятого
 * файла, после чего сохраняется журнал для отката. Пока идёт разрушительная часть,
 * cfg указывают на отдельную целую копию runtime, поэтому такой запуск остаётся
 * восстанавливаемым. Само существование исходников не заменяет portable-тест
 * холодного запуска обычного exe после убийства помощника.</p>
 */
