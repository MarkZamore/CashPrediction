package ru.cashprediction.core.update.lifecycle;

/**
 * Локальный контракт обновления для адаптеров запуска, независимый от установщика и HTTP.
 * Адаптер сообщает события, но не выбирает версию, источник, дельту или политику восстановления.
 * Реализация может быть заменена на границе сборки приложения без изменения этих потребителей.
 */
public interface UpdateSessionLifecycle extends AutoCloseable {
    /**
     * Выполняет локальный барьер до создания UI, без ожидания сети.
     * @return true при разрешении запуска; false при передаче управления предстартовому восстановлению
     */
    boolean beforeUi();

    /** Сообщает готовность UI; повторное событие не запускает второй сетевой проход. */
    void afterUiReady();

    /** Завершает подготовку и планирует установку после закрытия без обычного перезапуска. */
    @Override void close();
}
