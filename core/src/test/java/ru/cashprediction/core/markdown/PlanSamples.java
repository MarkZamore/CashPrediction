    /**
     * Номер строки (с 1), начинающейся с указанного текста.
     *
     * @param text   текст файла
     * @param prefix начало искомой строки
     * @return номер первой подходящей строки
     */
    public static int lineOf(String text, String prefix) {
        String[] lines = text.split("\\r\\n|\\n", -1);
        for (int i = 0; i < lines.length; i++) {
            if (lines[i].startsWith(prefix)) {
                return i + 1;
            }
        }
        throw new AssertionError("Строка не найдена: " + prefix);
    }
