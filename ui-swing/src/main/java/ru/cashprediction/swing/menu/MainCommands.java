package ru.cashprediction.swing.menu;

import java.time.LocalDate;
import java.util.List;

/**
 * Команды главного окна, которые нужны меню и панели инструментов, но не относятся к фасаду команд плана
 * ({@code SwingActions}): выход, список недавних планов, фокус на фильтр, переход к дате в таблице.
 *
 * <p>Реализуется главным окном. Вызывается только в потоке EDT.</p>
 */
public interface MainCommands {

    /** «Файл → Выход»: тот же путь, что закрытие главного окна (снимок, вопрос о сохранении, запись настроек). */
    void exit();

    /**
     * Недавние планы для подменю «Недавние».
     *
     * @return имена из настроек (имя файла в CashMemory или полный путь), последние — первыми
     */
    List<String> recentPlans();

    /** Ctrl+F: перевести фокус в поле фильтра таблицы. */
    void focusFilter();

    /**
     * Переключиться на таблицу и выделить первое событие не раньше даты.
     *
     * @param date дата
     */
    void showTableAt(LocalDate date);
}
